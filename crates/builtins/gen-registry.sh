#!/usr/bin/env bash
# Regenerates src/generated.rs from the local `nix` binary.
#
#   ./gen-registry.sh > src/generated.rs           # regenerate
#   diff <(./gen-registry.sh) src/generated.rs     # check
#
# For every attribute of `builtins` it records:
# - how it is bound in the global scope: `Bare` if `with { n = ...; }; n`
#   still yields the builtin (globals beat `with`), otherwise `Prefixed`
#   (available as `__n`);
# - its kind: `<PRIMOP>` -> PrimOp, `<LAMBDA>` -> NixDefined, else Value;
# - whether it still exists with `--option pure-eval true`.
set -euo pipefail

eval_nix() { nix-instantiate --eval -E "$1" 2>/dev/null; }

version=$(eval_nix 'builtins.nixVersion' | tr -d '"')
names=$(nix-instantiate --eval --strict --json -E 'builtins.attrNames builtins' | tr -d '[]"' | tr ',' ' ')
pure_names=" $(nix-instantiate --option pure-eval true --eval --strict --json -E 'builtins.attrNames builtins' | tr -d '[]"' | tr ',' ' ') "

echo "// @generated by gen-registry.sh from Nix ${version}. Do not edit by hand."
echo
echo "use crate::registry::{Global, Kind};"
echo
echo "/// \`(name, global binding, kind, in pure eval)\` for every attribute of \`builtins\`."
echo "#[rustfmt::skip]"
echo "pub(crate) const ENTRIES: &[(&str, Global, Kind, bool)] = &["
for n in $names; do
  if [ "$(eval_nix "with { \"$n\" = \"SENTINEL\"; }; $n" | head -c 12)" = '"SENTINEL"' ]; then
    global=Prefixed
    if [ -z "$(eval_nix "__$n" | head -c 1)" ]; then
      echo "error: builtin '$n' is neither a bare nor a __-prefixed global" >&2
      exit 1
    fi
  else
    global=Bare
  fi
  case "$(eval_nix "builtins.\"$n\"" | head -c 9)" in
    '<PRIMOP>'*) kind=PrimOp ;;
    '<LAMBDA>'*) kind=NixDefined ;;
    *) kind=Value ;;
  esac
  case "$pure_names" in
    *" $n "*) pure=true ;;
    *) pure=false ;;
  esac
  echo "    (\"$n\", Global::$global, Kind::$kind, $pure),"
done
echo "];"
